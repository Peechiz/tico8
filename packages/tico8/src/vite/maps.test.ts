it('refuses a map named as a tileset the file imports', () => {
  const sprites = ['tiles.png', 'rocks.png', 'player.png']
  expect(reason(sprites, 'tiles.json')).toBe(
    'it gives the name "tiles", which maps.ts already imports as a tileset from sprites.ts',
  )

  const root = project(sprites, {
    'rocks.json': room('tiles'),
    'cave.json': room('rocks'),
    // A sheet no map uses is not imported, so its name is free.
    'player.json': room('tiles'),
  })
  const { maps, problems } = scanMaps(root)
  expect(maps.map((entry) => entry.name)).toEqual(['cave', 'player'])
  expect(problems.map((problem) => problem.file)).toEqual(['rocks.json'])
  expect(biome(renderMaps(maps)).clean).toBe(true)
})

it('writes the file from the folders', () => {
  const root = project(['tiles.png', 'tiles.flags.json'], {
    'room1.json': room('tiles'),
    'broken.json': 'oops',
  })
  expect(writeMaps(root)).toEqual({
    changed: true,
    problems: [{ file: 'broken.json', reason: 'it is not valid JSON' }],
  })
  expect(generated(root)).toBe(layout)

  const bare = project([], {})
  expect(writeMaps(bare)).toEqual({ changed: true, problems: [] })
  expect(generated(bare)).toContain('export {}')
})

it('writes nothing for a project with no maps folder', () => {
  const root = project(['tiles.png'])
  expect(writeMaps(root)).toEqual({ changed: false, problems: [] })
  expect(existsSync(join(root, MAPS_FILE))).toBe(false)

  // A file already there is not taken away.
  writeFileSync(join(root, MAPS_FILE), 'mine')
  expect(writeMaps(root).changed).toBe(false)
  expect(generated(root)).toBe('mine')
})

it('leaves the file alone until its text would change', () => {
  const root = project(['tiles.png', 'rocks.png'], {
    'room1.json': room('tiles'),
  })
  const path = join(root, MAPS_FILE)
  writeMaps(root)
  // An old timestamp shows a rewrite even on a coarse clock.
  const old = new Date(2000, 0, 1)
  utimesSync(path, old, old)

  expect(writeMaps(root).changed).toBe(false)
  // New cells in a map are not a new list of maps.
  writeFileSync(
    join(root, MAPS_DIR, 'room1.json'),
    JSON.stringify({ tiles: 'tiles', layers: { walls: [' 4  4'] } }),
  )
  expect(writeMaps(root).changed).toBe(false)
  expect(statSync(path).mtime).toEqual(old)

  // Another tileset is.
  writeFileSync(join(root, MAPS_DIR, 'room1.json'), room('rocks'))
  expect(writeMaps(root).changed).toBe(true)
  expect(generated(root)).toContain('  tiles: rocks,\n')

  // So is a flags file arriving beside the tileset.
  writeFileSync(join(root, SPRITES_DIR, 'rocks.flags.json'), '{}')
  expect(writeMaps(root).changed).toBe(true)
  expect(generated(root)).toContain(
    "  flags: { url: '/sprites/rocks.flags.json', data: rocks_flags },\n",
  )
})
