it('refuses a name that cannot be imported', () => {
  const sprites = ['tiles.png']
  expect(reason(sprites, '2fast.json')).toMatch(/"2fast" starts with a digit/)
  expect(reason(sprites, '---.json')).toMatch(/no letters/)
  expect(reason(sprites, 'class.json')).toMatch(/"class" is a reserved word/)
  // The generated file imports `map`, so a map cannot take that name.
  expect(reason(sprites, 'map.json')).toBe(
    'the name "map" is taken by the function maps.ts imports',
  )
  expect(
    scanMaps(project(sprites, { 'sheet.json': room('tiles') })).maps,
  ).toEqual([{ name: 'sheet', file: 'sheet.json', tiles: 'tiles' }])
})

it('refuses two files that give one name', () => {
  const root = project(['tiles.png'], {
    'big-room.json': room('tiles'),
    'big_room.json': room('tiles'),
    'hall.json': room('tiles'),
  })
  const { maps, problems } = scanMaps(root)
  expect(maps.map((entry) => entry.name)).toEqual(['hall'])
  expect(problems).toEqual([
    {
      file: 'big-room.json',
      reason: 'it gives the name "bigRoom", and so does big_room.json',
    },
    {
      file: 'big_room.json',
      reason: 'it gives the name "bigRoom", and so does big-room.json',
    },
  ])
})

it('refuses a file that names no usable tileset', () => {
  const sprites = ['tiles.png', 'bad.12.png']
  expect(reason(sprites, 'room.json', '{ "tiles": ')).toBe(
    'it is not valid JSON',
  )
  expect(reason(sprites, 'room.json', '')).toBe('it is not valid JSON')
  expect(reason(sprites, 'room.json', '{ "layers": {} }')).toBe(
    'it names no tileset',
  )
  expect(reason(sprites, 'room.json', '{ "tiles": 3 }')).toBe(
    'it names no tileset',
  )
  expect(reason(sprites, 'room.json', '[]')).toBe('it names no tileset')
  expect(reason(sprites, 'room.json', 'null')).toBe('it names no tileset')
  expect(reason(sprites, 'room.json', room('rocks'))).toBe(
    'its tileset "rocks" is not a sheet in the sprites folder',
  )
  // A PNG that `sprites.ts` leaves out is not a sheet.
  expect(reason(sprites, 'room.json', room('bad'))).toBe(
    'its tileset "bad" is not a sheet in the sprites folder',
  )
  // The layers are the page's to check.
  const root = project(sprites, { 'room.json': '{ "tiles": "tiles" }' })
  expect(scanMaps(root).problems).toEqual([])
})

