/** The repository, whose `biome.json` the generated text has to satisfy. */
const repo = join(import.meta.dirname, '../../../..')

const roots: string[] = []

function folder(): string {
  const root = mkdtempSync(join(tmpdir(), 'tico8-maps-'))
  roots.push(root)
  return root
}

/** The text of a map file that uses this tileset. */
function room(tiles: string): string {
  return JSON.stringify({ tiles, layers: { ground: [' 1  1', ' 1  1'] } })
}

/**
 * A project folder. `sprites` are file names, written empty; `maps` are
 * file names with their text. Leave `maps` out for no maps folder.
 */
function project(
  sprites: readonly string[],
  maps?: Readonly<Record<string, string>>,
): string {
  const root = folder()
  mkdirSync(join(root, SPRITES_DIR))
  for (const file of sprites) writeFileSync(join(root, SPRITES_DIR, file), '')
  if (maps) {
    mkdirSync(join(root, MAPS_DIR))
    for (const [file, text] of Object.entries(maps)) {
      writeFileSync(join(root, MAPS_DIR, file), text)
    }
  }
  return root
}

function generated(root: string): string {
  return readFileSync(join(root, MAPS_FILE), 'utf8')
}

/** Why the one map of a project is left out. */
function reason(
  sprites: readonly string[],
  file: string,
  text = room('tiles'),
): string {
  const { maps, problems } = scanMaps(project(sprites, { [file]: text }))
  expect(maps).toEqual([])
  expect(problems).toHaveLength(1)
  expect(problems[0]!.file).toBe(file)
  return problems[0]!.reason
}

/**
 * What Biome makes of a generated file under the repository's settings:
 * the text it would rewrite it to, and whether it has anything to report.
 * Run in a folder outside the repository, with the settings copied there.
 */
function biome(text: string): { text: string; clean: boolean } {
  const dir = folder()
  const config = JSON.parse(readFileSync(join(repo, 'biome.json'), 'utf8'))
  // The folder is not in a git repository, and has no schema beside it.
  delete config.vcs
  delete config.$schema
  writeFileSync(join(dir, 'biome.json'), JSON.stringify(config))
  writeFileSync(join(dir, MAPS_FILE), text)

  const bin = join(repo, 'node_modules/.bin/biome')
  const run = (...args: string[]) =>
    execFileSync(bin, ['check', ...args, MAPS_FILE], {
      cwd: dir,
      stdio: 'pipe',
    })
  let clean = true
  try {
    run('--error-on-warnings')
  } catch {
    clean = false
  }
  try {
    run('--write')
  } catch {
    clean = false
  }
  return { text: generated(dir), clean }
}

