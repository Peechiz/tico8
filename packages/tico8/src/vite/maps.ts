import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import type { Plugin } from 'vite'
import { camelCase, SPRITES_DIR, SPRITES_FILE, scanSprites } from './sprites.ts'

/** The project folder maps live in, and the file written beside it. */
export const MAPS_DIR = 'maps'
export const MAPS_FILE = 'maps.ts'

/** What ends the name of a tileset's flags file: `tiles.flags.json`. */
export const FLAGS_SUFFIX = '.flags.json'

export interface MapEntry {
  /** The name game code imports: `room1` for `room1.json`. */
  name: string
  /** The file name inside the maps folder. */
  file: string
  /** The tileset: the name its sheet is imported by from `sprites.ts`. */
  tiles: string
  /** The tileset's flags file inside the sprites folder, if it has one. */
  flags?: string
}

/** A file in the maps folder that was left out, and why. */
export interface MapProblem {
  file: string
  reason: string
}

/** The longest line the formatter leaves on one line. */
const lineWidth = 80

const header = '// Generated by tico8 from the maps folder. Do not edit.\n'

/** What the generated file imports the sheets from: `./sprites`. */
const spritesModule = `./${SPRITES_FILE.replace(/\.ts$/, '')}`

/**
 * Names the generated file cannot export: the words the language keeps for
 * itself. `sprites.ts` keeps the same list, and adds `sheet`.
 */
const reserved = new Set(
  (
    'arguments await break case catch class const continue debugger default ' +
    'delete do else enum eval export extends false finally for function if ' +
    'implements import in instanceof interface let new null package private ' +
    'protected public return static super switch this throw true try ' +
    'typeof undefined var void while with yield'
  ).split(' '),
)

/**
 * The text of the generated `maps.ts`. It is written the way the formatter
 * would leave it, imports in the formatter's order, because examples check
 * the file in and the linter reads it.
 */
export function renderMaps(maps: readonly MapEntry[]): string {
  if (maps.length === 0) return `${header}export {}\n`
  const sorted = [...maps].sort((a, b) => compare(a.name, b.name))

  const mapImports = sorted.map(({ name, file }) => ({
    local: `${name}_map`,
    source: `./${MAPS_DIR}/${file}`,
  }))
  const sheets = [...new Set(sorted.map((entry) => entry.tiles))]
  const flagFiles = new Map<string, string>()
  for (const { tiles, flags } of sorted) {
    if (flags !== undefined) flagFiles.set(tiles, flags)
  }
  const flagImports = [...flagFiles].map(([tiles, file]) => ({
    local: `${tiles}_flags`,
    source: `./${SPRITES_DIR}/${file}`,
  }))

  const lines = [
    "import { map } from 'tico8/assets'",
    ...defaultImports(mapImports),
    namedImport(sheets, spritesModule),
    ...defaultImports(flagImports),
    '',
  ]
  for (const { name, file, tiles, flags } of sorted) {
    lines.push(
      `export const ${name} = map({`,
      `  url: ${address(MAPS_DIR, file)},`,
      `  data: ${name}_map,`,
      tiles === 'tiles' ? '  tiles,' : `  tiles: ${tiles},`,
    )
    if (flags !== undefined) {
      const url = address(SPRITES_DIR, flags)
      const line = `  flags: { url: ${url}, data: ${tiles}_flags },`
      if (line.length <= lineWidth) lines.push(line)
      // Broken the way the formatter breaks an object that is too long.
      else
        lines.push(
          '  flags: {',
          `    url: ${url},`,
          `    data: ${tiles}_flags,`,
          '  },',
        )
    }
    lines.push('})')
  }
  return `${header}${lines.join('\n')}\n`
}

/**
 * The maps in a project's maps folder, sorted by name, and the files left
 * out. A folder that is missing counts as empty.
 */
export function scanMaps(root: string): {
  maps: MapEntry[]
  problems: MapProblem[]
} {
  const named: { name: string; file: string }[] = []
  const problems: MapProblem[] = []
  for (const file of listFiles(join(root, MAPS_DIR))) {
    // Hidden files are an editor's or the system's, never a map.
    if (file.startsWith('.') || !/\.json$/i.test(file)) continue
    const name = camelCase(file.slice(0, -'.json'.length))
    const reason = nameProblem(name)
    if (reason === undefined) named.push({ name, file })
    else problems.push({ file, reason })
  }

  const byName = new Map<string, string[]>()
  for (const { name, file } of named) {
    byName.set(name, [...(byName.get(name) ?? []), file])
  }

  const sheets = new Set(scanSprites(root).sheets.map((sheet) => sheet.name))
  const flagFiles = scanFlags(root)
  const found: MapEntry[] = []
  for (const { name, file } of named) {
    const same = byName.get(name)!
    if (same.length > 1) {
      const others = same.filter((other) => other !== file)
      problems.push({
        file,
        reason: `it gives the name "${name}", and so does ${others.join(' and ')}`,
      })
      continue
    }
    const tiles = readTileset(join(root, MAPS_DIR, file))
    if (typeof tiles !== 'string') {
      problems.push({ file, reason: tiles.reason })
      continue
    }
    if (!sheets.has(tiles)) {
      problems.push({
        file,
        reason: `its tileset "${tiles}" is not a sheet in the ${SPRITES_DIR} folder`,
      })
      continue
    }
    const flags = flagFiles.get(tiles) ?? []
    if (flags.length > 1) {
      problems.push({
        file,
        reason: `its tileset "${tiles}" has more than one flags file: ${flags.join(' and ')}`,
      })
      continue
    }
    found.push(
      flags.length === 1
        ? { name, file, tiles, flags: flags[0]! }
        : { name, file, tiles },
    )
  }

  // The file imports every tileset by name, so no map can take one's name.
  const imported = new Set(found.map((entry) => entry.tiles))
  const maps: MapEntry[] = []
  for (const entry of found) {
    if (!imported.has(entry.name)) {
      maps.push(entry)
      continue
    }
    problems.push({
      file: entry.file,
      reason: `it gives the name "${entry.name}", which ${MAPS_FILE} already imports as a tileset from ${SPRITES_FILE}`,
    })
  }

  maps.sort((a, b) => compare(a.name, b.name))
  problems.sort((a, b) => compare(a.file, b.file))
  return { maps, problems }
}

/**
 * Bring a project's `maps.ts` in step with its maps folder. A project
 * with no maps folder gets no file. The file is written only when its
 * text would change; `changed` says whether it was.
 */
export function writeMaps(root: string): {
  changed: boolean
  problems: MapProblem[]
} {
  // A file already there is left alone: it may not be ours to delete.
  if (!isFolder(join(root, MAPS_DIR))) return { changed: false, problems: [] }
  const { maps, problems } = scanMaps(root)
  const text = renderMaps(maps)
  const path = join(root, MAPS_FILE)
  if (readText(path) === text) return { changed: false, problems }
  writeFileSync(path, text)
  return { changed: true, problems }
}

/** Keeps the project's `maps.ts` in step with its maps and sprites folders. */
export function maps(): Plugin {
  let root = ''
  let warn: (message: string) => void = () => {}
  /** Warnings already shown, so a problem is reported once, not per scan. */
  let shown = new Set<string>()

  function sync() {
    const { problems } = writeMaps(root)
    const messages = problems.map(
      ({ file, reason }) =>
        `[tico8] ${MAPS_DIR}/${file} is left out of ${MAPS_FILE}: ${reason}.`,
    )
    for (const message of messages) {
      if (!shown.has(message)) warn(message)
    }
    shown = new Set(messages)
  }

  return {
    name: 'tico8:maps',

    configResolved(config) {
      root = resolve(config.root)
      warn = (message) => config.logger.warn(message, { timestamp: true })
      // Here rather than on the first request, so the file exists before
      // anything imports it.
      sync()
    },

    configureServer(server) {
      const dirs = [join(root, MAPS_DIR), join(root, SPRITES_DIR)]
      const out = join(root, MAPS_FILE)
      let timer: ReturnType<typeof setTimeout> | undefined

      server.watcher.on('all', (_event, changed) => {
        const path = resolve(changed)
        // A saved map counts too: it may name another tileset. When it only
        // has new cells the text comes out the same and nothing is written.
        const listed = dirs.some((dir) => path === dir || dirname(path) === dir)
        // A generated file edited or deleted by hand is put back.
        if (!listed && path !== out) return
        // A rename arrives as a removal and an addition; wait for both.
        clearTimeout(timer)
        timer = setTimeout(sync, 50)
      })
      server.httpServer?.once('close', () => clearTimeout(timer))
    },
  }
}

/** Why a name cannot be exported from the generated file, if it cannot. */
function nameProblem(name: string): string | undefined {
  if (name === '') return 'it has no letters to make a name from'
  if (/^\p{N}/u.test(name)) {
    return `the name "${name}" starts with a digit, so it cannot be imported`
  }
  if (reserved.has(name)) {
    return `"${name}" is a reserved word, so it cannot be imported`
  }
  if (name === 'map') {
    return `the name "map" is taken by the function ${MAPS_FILE} imports`
  }
  if (!/^\p{ID_Start}\p{ID_Continue}*$/u.test(name)) {
    return `the name "${name}" cannot be used as an import`
  }
  return undefined
}

/**
 * The tileset a map file names, or why it names none. The layers are not
 * looked at: the page reports those.
 */
function readTileset(path: string): string | { reason: string } {
  let data: unknown
  try {
    data = JSON.parse(readFileSync(path, 'utf8'))
  } catch (error) {
    // A file removed since the folder was listed is gone by the next scan.
    if (!(error instanceof SyntaxError) && !isMissing(error)) throw error
    return { reason: 'it is not valid JSON' }
  }
  const tiles = (data as { tiles?: unknown } | null)?.tiles
  if (typeof tiles !== 'string' || tiles === '') {
    return { reason: 'it names no tileset' }
  }
  return tiles
}

/**
 * The flags files in the sprites folder, by the name of the sheet each
 * belongs to: `tiles.flags.json` belongs to `tiles.png` or `tiles.16.png`.
 */
function scanFlags(root: string): Map<string, string[]> {
  const bySheet = new Map<string, string[]>()
  for (const file of listFiles(join(root, SPRITES_DIR)).sort(compare)) {
    if (file.startsWith('.') || !file.endsWith(FLAGS_SUFFIX)) continue
    const sheet = camelCase(file.slice(0, -FLAGS_SUFFIX.length))
    bySheet.set(sheet, [...(bySheet.get(sheet) ?? []), file])
  }
  return bySheet
}

/** A file's address on the dev server, as `sprites.ts` spells its own. */
function address(dir: string, file: string): string {
  return `'/${dir}/${encodeURIComponent(file).replaceAll("'", '%27')}'`
}

/**
 * An import path as the formatter writes a string: in single quotes, or in
 * double quotes when that needs fewer escapes.
 */
function quote(source: string): string {
  const text = source.replaceAll('\\', '\\\\')
  const singles = text.split("'").length - 1
  const doubles = text.split('"').length - 1
  return singles > doubles
    ? `"${text.replaceAll('"', '\\"')}"`
    : `'${text.replaceAll("'", "\\'")}'`
}

/** Default imports, one a line, in the formatter's order of their paths. */
function defaultImports(
  imports: readonly { local: string; source: string }[],
): string[] {
  return imports
    .map(({ local, source }) => ({ local, source: quote(source) }))
    .sort((a, b) =>
      compareSources(a.source.slice(1, -1), b.source.slice(1, -1)),
    )
    .map(({ local, source }) => `import ${local} from ${source}`)
}

/** A named import, its names in the formatter's order. */
function namedImport(names: readonly string[], source: string): string {
  const sorted = [...names].sort(compareSources)
  const line = `import { ${sorted.join(', ')} } from ${quote(source)}`
  if (line.length <= lineWidth) return line
  // Broken the way the formatter breaks an import that is too long.
  return `import {\n${sorted.map((name) => `  ${name},`).join('\n')}\n} from ${quote(source)}`
}

/**
 * Where the formatter puts each ASCII mark when it sorts imports, lowest
 * first. Digits come after these, then letters, then everything else.
 */
const marks = '\\?#=&;,@:. _-+*!%$()[]{}<>|^~\'"`'

/** One character's place in the formatter's order: `A`, `a`, `B`, `b`. */
function rank(char: string): number {
  const code = char.codePointAt(0)!
  if (code > 0x7f) return 1000 + code
  if (char >= '0' && char <= '9') return 100 + code
  if (char >= 'A' && char <= 'Z') return 200 + (code - 65) * 2
  if (char >= 'a' && char <= 'z') return 201 + (code - 97) * 2
  return marks.indexOf(char)
}

function isDigit(char: string | undefined): boolean {
  return char !== undefined && char >= '0' && char <= '9'
}

/**
 * The order the formatter sorts import paths and imported names in. It is
 * read as the path is written, escapes and all. A shorter run of digits
 * comes before a longer one, so `room2` is before `room10`.
 */
function compareSources(a: string, b: string): number {
  const x = Array.from(a)
  const y = Array.from(b)
  let i = 0
  while (i < x.length && i < y.length) {
    if (isDigit(x[i]) && isDigit(y[i])) {
      let end = i
      while (isDigit(x[end]) && isDigit(y[end])) end++
      if (isDigit(x[end])) return 1
      if (isDigit(y[end])) return -1
      // Runs of one length are in order when their digits are.
      for (; i < end; i++) {
        if (x[i] !== y[i]) return x[i]! < y[i]! ? -1 : 1
      }
      continue
    }
    const order = rank(x[i]!) - rank(y[i]!)
    if (order !== 0) return order
    i++
  }
  return x.length - y.length
}

/** Code-unit order, so the output is the same on every machine. */
function compare(a: string, b: string): number {
  return a < b ? -1 : a > b ? 1 : 0
}

/** The names of the files directly inside a folder; none if it is missing. */
function listFiles(dir: string): string[] {
  try {
    return readdirSync(dir, { withFileTypes: true })
      .filter((entry) => entry.isFile())
      .map((entry) => entry.name)
  } catch (error) {
    if (isMissing(error)) return []
    throw error
  }
}

function isFolder(path: string): boolean {
  try {
    return statSync(path).isDirectory()
  } catch (error) {
    if (isMissing(error)) return false
    throw error
  }
}

function readText(path: string): string | undefined {
  try {
    return readFileSync(path, 'utf8')
  } catch (error) {
    if (isMissing(error)) return undefined
    throw error
  }
}

function isMissing(error: unknown): boolean {
  const code = (error as NodeJS.ErrnoException | undefined)?.code
  return code === 'ENOENT' || code === 'ENOTDIR'
}
