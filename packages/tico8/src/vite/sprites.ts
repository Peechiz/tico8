import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import type { Plugin } from 'vite'

/** The project folder sheets live in, and the file written beside it. */
export const SPRITES_DIR = 'sprites'
export const SPRITES_FILE = 'sprites.ts'

export interface SheetFile {
  /** The name game code imports: `player` for `player.16.png`. */
  name: string
  /** The file name inside the sprites folder. */
  file: string
  cellWidth: number
  cellHeight: number
}

/** A PNG in the sprites folder that was left out, and why. */
export interface SheetProblem {
  file: string
  reason: string
}

/** Thrown by `parseSheetFile` for a PNG whose name cannot be used. */
export class SheetFileError extends Error {
  file: string
  reason: string

  constructor(file: string, reason: string) {
    super(`${file}: ${reason}`)
    this.name = 'SheetFileError'
    this.file = file
    this.reason = reason
  }
}

/** The side of a cell when the file name gives no size. */
const defaultCell = 8

/** The longest line the formatter leaves on one line. */
const lineWidth = 80

const header = '// Generated by tico8 from the sprites folder. Do not edit.\n'

/**
 * Names the generated file cannot export: words the language keeps for
 * itself, and `sheet`, which the file imports.
 */
const reserved = new Set(
  (
    'arguments await break case catch class const continue debugger default ' +
    'delete do else enum eval export extends false finally for function if ' +
    'implements import in instanceof interface let new null package private ' +
    'protected public return sheet static super switch this throw true try ' +
    'typeof undefined var void while with yield'
  ).split(' '),
)

/**
 * Turn a file's base name into the name it is imported by: `big-boss`,
 * `big_boss` and `big boss` all give `bigBoss`. Anything that is not a
 * letter or a digit separates words.
 */
export function camelCase(text: string): string {
  const words = text.split(/[^\p{L}\p{N}]+/u).filter((word) => word !== '')
  return words
    .map((word, index) => {
      if (index > 0) return word.charAt(0).toUpperCase() + word.slice(1)
      // `UI` reads better as `ui` than as `uI`.
      if (word === word.toUpperCase()) return word.toLowerCase()
      return word.charAt(0).toLowerCase() + word.slice(1)
    })
    .join('')
}

/**
 * Read a sheet's name and cell size from its file name: `player.png` is
 * 8x8, `player.16.png` is 16x16, `player.16x24.png` is 16 wide and 24 tall.
 * Returns undefined for a file that is not a PNG, and throws a
 * `SheetFileError` for a PNG whose name or cell size cannot be used.
 */
export function parseSheetFile(file: string): SheetFile | undefined {
  // Hidden files are an editor's or the system's, never a sheet.
  if (file.startsWith('.') || !/\.png$/i.test(file)) return undefined
  const stem = file.slice(0, -'.png'.length)

  const sized = /^(.*)\.(\d+)(?:x(\d+))?$/.exec(stem)
  const base = sized ? sized[1]! : stem
  const cellWidth = sized ? Number(sized[2]) : defaultCell
  const cellHeight = sized ? Number(sized[3] ?? sized[2]) : defaultCell
  for (const size of [cellWidth, cellHeight]) {
    if (size < 8 || size % 8 !== 0) {
      throw new SheetFileError(
        file,
        `a cell size of ${size} is not a multiple of 8`,
      )
    }
  }

  const name = camelCase(base)
  if (name === '') {
    throw new SheetFileError(file, 'it has no letters to make a name from')
  }
  if (/^\p{N}/u.test(name)) {
    throw new SheetFileError(
      file,
      `the name "${name}" starts with a digit, so it cannot be imported`,
    )
  }
  if (reserved.has(name)) {
    throw new SheetFileError(
      file,
      `"${name}" is a reserved word, so it cannot be imported`,
    )
  }
  if (!/^\p{ID_Start}\p{ID_Continue}*$/u.test(name)) {
    throw new SheetFileError(
      file,
      `the name "${name}" cannot be used as an import`,
    )
  }
  return { name, file, cellWidth, cellHeight }
}

/** The text of the generated `sprites.ts`. */
export function renderSprites(files: readonly SheetFile[]): string {
  if (files.length === 0) return `${header}export {}\n`
  const lines = [...files]
    .sort((a, b) => compare(a.name, b.name))
    .map(({ name, file, cellWidth, cellHeight }) => {
      const url = `'/${SPRITES_DIR}/${encodeURIComponent(file).replaceAll("'", '%27')}'`
      const line = `export const ${name} = sheet(${url}, ${cellWidth}, ${cellHeight})`
      if (line.length <= lineWidth) return line
      // Broken the way the formatter breaks a call that is too long.
      return `export const ${name} = sheet(\n  ${url},\n  ${cellWidth},\n  ${cellHeight},\n)`
    })
  return `${header}import { sheet } from 'tico8/assets'\n\n${lines.join('\n')}\n`
}

/**
 * The sheets in a project's sprites folder, sorted by name, and the PNGs
 * left out. A folder that is missing counts as empty.
 */
export function scanSprites(root: string): {
  sheets: SheetFile[]
  problems: SheetProblem[]
} {
  const parsed: SheetFile[] = []
  const problems: SheetProblem[] = []
  for (const file of listFiles(join(root, SPRITES_DIR))) {
    try {
      const sheet = parseSheetFile(file)
      if (sheet) parsed.push(sheet)
    } catch (error) {
      if (!(error instanceof SheetFileError)) throw error
      problems.push({ file, reason: error.reason })
    }
  }

  const byName = new Map<string, SheetFile[]>()
  for (const sheet of parsed) {
    byName.set(sheet.name, [...(byName.get(sheet.name) ?? []), sheet])
  }
  const sheets: SheetFile[] = []
  for (const [name, same] of byName) {
    if (same.length === 1) {
      sheets.push(same[0]!)
      continue
    }
    for (const { file } of same) {
      const others = same.filter((other) => other.file !== file)
      problems.push({
        file,
        reason: `it gives the name "${name}", and so does ${others
          .map((other) => other.file)
          .join(' and ')}`,
      })
    }
  }

  sheets.sort((a, b) => compare(a.name, b.name))
  problems.sort((a, b) => compare(a.file, b.file))
  return { sheets, problems }
}

/**
 * Bring a project's `sprites.ts` in step with its sprites folder. The file
 * is written only when its text would change; `changed` says whether it was.
 */
export function writeSprites(root: string): {
  changed: boolean
  problems: SheetProblem[]
} {
  const { sheets, problems } = scanSprites(root)
  const text = renderSprites(sheets)
  const path = join(root, SPRITES_FILE)
  if (readText(path) === text) return { changed: false, problems }
  writeFileSync(path, text)
  return { changed: true, problems }
}

/** Keeps the project's `sprites.ts` in step with its sprites folder. */
export function sprites(): Plugin {
  let root = ''
  let warn: (message: string) => void = () => {}
  /** Warnings already shown, so a problem is reported once, not per scan. */
  let shown = new Set<string>()

  function sync() {
    const { problems } = writeSprites(root)
    const messages = problems.map(
      ({ file, reason }) =>
        `[tico8] ${SPRITES_DIR}/${file} is left out of ${SPRITES_FILE}: ${reason}.`,
    )
    for (const message of messages) {
      if (!shown.has(message)) warn(message)
    }
    shown = new Set(messages)
  }

  return {
    name: 'tico8:sprites',

    configResolved(config) {
      root = resolve(config.root)
      warn = (message) => config.logger.warn(message, { timestamp: true })
      // Here rather than on the first request, so the file exists before
      // anything imports it.
      sync()
    },

    configureServer(server) {
      const dir = join(root, SPRITES_DIR)
      const out = join(root, SPRITES_FILE)
      let timer: ReturnType<typeof setTimeout> | undefined

      server.watcher.on('all', (event, changed) => {
        const path = resolve(changed)
        // The folder's list of files is what matters. A PNG saved with new
        // pixels keeps its name, and is swapped live elsewhere.
        const listed =
          event !== 'change' && (path === dir || dirname(path) === dir)
        // A generated file edited or deleted by hand is put back.
        if (!listed && path !== out) return
        // A rename arrives as a removal and an addition; wait for both.
        clearTimeout(timer)
        timer = setTimeout(sync, 50)
      })
      server.httpServer?.once('close', () => clearTimeout(timer))
    },
  }
}

/** Code-unit order, so the output is the same on every machine. */
function compare(a: string, b: string): number {
  return a < b ? -1 : a > b ? 1 : 0
}

/** The names of the files directly inside a folder; none if it is missing. */
function listFiles(dir: string): string[] {
  try {
    return readdirSync(dir, { withFileTypes: true })
      .filter((entry) => entry.isFile())
      .map((entry) => entry.name)
  } catch (error) {
    if (isMissing(error)) return []
    throw error
  }
}

function readText(path: string): string | undefined {
  try {
    return readFileSync(path, 'utf8')
  } catch (error) {
    if (isMissing(error)) return undefined
    throw error
  }
}

function isMissing(error: unknown): boolean {
  const code = (error as NodeJS.ErrnoException | undefined)?.code
  return code === 'ENOENT' || code === 'ENOTDIR'
}
