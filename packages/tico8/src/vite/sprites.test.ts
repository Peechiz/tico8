import {
  mkdirSync,
  mkdtempSync,
  readFileSync,
  renameSync,
  rmSync,
  statSync,
  utimesSync,
  writeFileSync,
} from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { afterEach, expect, it } from 'vitest'
import {
  camelCase,
  parseSheetFile,
  renderSprites,
  SheetFileError,
  SPRITES_DIR,
  SPRITES_FILE,
  scanSprites,
  writeSprites,
} from './sprites.ts'

const roots: string[] = []

/** A project folder holding empty files with these names as its sprites. */
function project(files?: readonly string[]): string {
  const root = mkdtempSync(join(tmpdir(), 'tico8-sprites-'))
  roots.push(root)
  if (files) {
    mkdirSync(join(root, SPRITES_DIR))
    for (const file of files) writeFileSync(join(root, SPRITES_DIR, file), '')
  }
  return root
}

function generated(root: string): string {
  return readFileSync(join(root, SPRITES_FILE), 'utf8')
}

/** Why a PNG's name is refused. */
function reason(file: string): string {
  try {
    parseSheetFile(file)
  } catch (error) {
    if (error instanceof SheetFileError) return error.reason
    throw error
  }
  throw new Error(`${file} was accepted`)
}

afterEach(() => {
  for (const root of roots.splice(0)) {
    rmSync(root, { recursive: true, force: true })
  }
})

it('reads the cell size from the file name', () => {
  expect(parseSheetFile('player.png')).toEqual({
    name: 'player',
    file: 'player.png',
    cellWidth: 8,
    cellHeight: 8,
  })
  expect(parseSheetFile('player.16.png')).toEqual({
    name: 'player',
    file: 'player.16.png',
    cellWidth: 16,
    cellHeight: 16,
  })
  expect(parseSheetFile('player.16x24.png')).toEqual({
    name: 'player',
    file: 'player.16x24.png',
    cellWidth: 16,
    cellHeight: 24,
  })
  expect(parseSheetFile('PLAYER.8.PNG')).toMatchObject({
    name: 'player',
    file: 'PLAYER.8.PNG',
    cellWidth: 8,
  })
})

it('ignores files that are not PNGs', () => {
  expect(parseSheetFile('player.jpg')).toBeUndefined()
  expect(parseSheetFile('player.png.bak')).toBeUndefined()
  expect(parseSheetFile('notes.txt')).toBeUndefined()
  expect(parseSheetFile('png')).toBeUndefined()
  expect(parseSheetFile('.DS_Store')).toBeUndefined()
  expect(parseSheetFile('._player.png')).toBeUndefined()
})

it('turns file names into camelCase', () => {
  expect(camelCase('big-boss')).toBe('bigBoss')
  expect(camelCase('big_boss')).toBe('bigBoss')
  expect(camelCase('big boss')).toBe('bigBoss')
  expect(camelCase('bigBoss')).toBe('bigBoss')
  expect(camelCase('BigBoss')).toBe('bigBoss')
  expect(camelCase('UI')).toBe('ui')
  expect(camelCase('--level__2  tiles-')).toBe('level2Tiles')
  expect(camelCase('player.v2')).toBe('playerV2')
  expect(camelCase('---')).toBe('')

  expect(parseSheetFile('big-boss.16.png')?.name).toBe('bigBoss')
  expect(parseSheetFile('big_boss.png')?.name).toBe('bigBoss')
  expect(parseSheetFile('big boss.png')?.name).toBe('bigBoss')
})

it('refuses a cell size that is not a multiple of 8', () => {
  expect(reason('player.12.png')).toBe(
    'a cell size of 12 is not a multiple of 8',
  )
  expect(reason('player.0.png')).toMatch(/cell size of 0/)
  expect(reason('player.4.png')).toMatch(/cell size of 4/)
  expect(reason('player.16x20.png')).toMatch(/cell size of 20/)
  expect(reason('player.7x16.png')).toMatch(/cell size of 7/)
})

it('refuses a name that cannot be imported', () => {
  expect(reason('2fast.png')).toMatch(/"2fast" starts with a digit/)
  expect(reason('16.png')).toMatch(/starts with a digit/)
  expect(reason('.png'.padStart(7, '-'))).toMatch(/no letters/)
  expect(reason('_.16.png')).toMatch(/no letters/)
  expect(reason('class.png')).toMatch(/"class" is a reserved word/)
  expect(reason('new.16.png')).toMatch(/reserved word/)
  // The generated file imports `sheet`, so a sheet cannot take that name.
  expect(reason('sheet.png')).toMatch(/reserved word/)
  expect(() => parseSheetFile('class.png')).toThrow('class.png: ')
})

it('renders the generated file, sorted by name', () => {
  const tiles = parseSheetFile('tiles.png')!
  const player = parseSheetFile('player.16.png')!
  expect(renderSprites([tiles, player])).toBe(
    `// Generated by tico8 from the sprites folder. Do not edit.
import { sheet } from 'tico8/assets'

export const player = sheet('/sprites/player.16.png', 16, 16)
export const tiles = sheet('/sprites/tiles.png', 8, 8)
`,
  )
})

it('renders an empty module for no sheets', () => {
  expect(renderSprites([])).toBe(
    `// Generated by tico8 from the sprites folder. Do not edit.
export {}
`,
  )
})

it('encodes the URL and breaks a line that is too long', () => {
  expect(renderSprites([parseSheetFile("big boss's.16x24.png")!])).toContain(
    "export const bigBossS = sheet('/sprites/big%20boss%27s.16x24.png', 16, 24)\n",
  )
  const long = `${'a'.repeat(40)}.png`
  expect(renderSprites([parseSheetFile(long)!])).toContain(
    `export const ${'a'.repeat(40)} = sheet(
  '/sprites/${long}',
  8,
  8,
)
`,
  )
})

it('scans a folder, skipping what it cannot use', () => {
  const root = project([
    'tiles.png',
    'player.16.png',
    'big boss.16x24.png',
    'notes.txt',
    '2fast.png',
    'odd.12.png',
    'enemy.png',
    'enemy.16.png',
  ])
  mkdirSync(join(root, SPRITES_DIR, 'nested.png'))
  writeFileSync(join(root, SPRITES_DIR, 'nested.png', 'deep.png'), '')

  const { sheets, problems } = scanSprites(root)
  expect(sheets.map((sheet) => sheet.name)).toEqual([
    'bigBoss',
    'player',
    'tiles',
  ])
  expect(problems).toEqual([
    { file: '2fast.png', reason: expect.stringMatching(/digit/) },
    {
      file: 'enemy.16.png',
      reason: 'it gives the name "enemy", and so does enemy.png',
    },
    {
      file: 'enemy.png',
      reason: 'it gives the name "enemy", and so does enemy.16.png',
    },
    { file: 'odd.12.png', reason: expect.stringMatching(/multiple of 8/) },
  ])
})

it('writes the file from the folder', () => {
  const root = project(['tiles.png', 'player.16.png', 'readme.md'])
  expect(writeSprites(root)).toEqual({ changed: true, problems: [] })
  expect(generated(root)).toBe(
    `// Generated by tico8 from the sprites folder. Do not edit.
import { sheet } from 'tico8/assets'

export const player = sheet('/sprites/player.16.png', 16, 16)
export const tiles = sheet('/sprites/tiles.png', 8, 8)
`,
  )
})

it('writes an empty module when the folder is empty or missing', () => {
  const empty = `// Generated by tico8 from the sprites folder. Do not edit.
export {}
`
  const missing = project()
  expect(writeSprites(missing).changed).toBe(true)
  expect(generated(missing)).toBe(empty)

  const bare = project([])
  expect(writeSprites(bare).changed).toBe(true)
  expect(generated(bare)).toBe(empty)
})

it('leaves the file alone until the list of sheets changes', () => {
  const root = project(['tiles.png', 'player.16.png'])
  const path = join(root, SPRITES_FILE)
  writeSprites(root)
  // An old timestamp shows a rewrite even on a coarse clock.
  const old = new Date(2000, 0, 1)
  utimesSync(path, old, old)

  expect(writeSprites(root).changed).toBe(false)
  // New pixels in a sheet are not a new list of sheets.
  writeFileSync(join(root, SPRITES_DIR, 'player.16.png'), 'repainted')
  expect(writeSprites(root).changed).toBe(false)
  expect(statSync(path).mtime).toEqual(old)

  renameSync(
    join(root, SPRITES_DIR, 'player.16.png'),
    join(root, SPRITES_DIR, 'hero.16.png'),
  )
  expect(writeSprites(root).changed).toBe(true)
  expect(generated(root)).toContain("export const hero = sheet('/sprites/hero")
  expect(generated(root)).not.toContain('player')

  rmSync(join(root, SPRITES_DIR), { recursive: true })
  expect(writeSprites(root).changed).toBe(true)
  expect(generated(root)).toContain('export {}')
})
