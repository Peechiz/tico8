import {
  existsSync,
  mkdirSync,
  mkdtempSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { afterEach, expect, it } from 'vitest'
import {
  renderSounds,
  SOUNDS_DIR,
  SOUNDS_FILE,
  scanSounds,
  writeSounds,
} from './sounds.ts'

const roots: string[] = []

/** A project folder holding empty files with these names as its sounds. */
function project(files?: readonly string[]): string {
  const root = mkdtempSync(join(tmpdir(), 'tico8-sounds-'))
  roots.push(root)
  if (files) {
    mkdirSync(join(root, SOUNDS_DIR))
    for (const file of files) writeFileSync(join(root, SOUNDS_DIR, file), '')
  }
  return root
}

function generated(root: string): string {
  return readFileSync(join(root, SOUNDS_FILE), 'utf8')
}

afterEach(() => {
  for (const root of roots.splice(0)) {
    rmSync(root, { recursive: true, force: true })
  }
})

it('writes the form the plan gives', () => {
  const root = project(['theme.ogg', 'swing.wav', 'Big-Boss.MP3'])
  expect(writeSounds(root)).toEqual({ changed: true, problems: [] })
  expect(
    generated(root),
  ).toBe(`// Generated by tico8 from the sounds folder. Do not edit.
import { sound } from 'tico8/assets'

export const bigBoss = sound('/sounds/Big-Boss.MP3')
export const swing = sound('/sounds/swing.wav')
export const theme = sound('/sounds/theme.ogg')
`)
  expect(writeSounds(root).changed).toBe(false)
})

it('leaves out both files that take the same name', () => {
  const root = project(['jump.wav', 'jump.ogg', 'hit.wav'])
  const { sounds, problems } = scanSounds(root)
  expect(sounds).toEqual([{ name: 'hit', file: 'hit.wav' }])
  expect(problems).toEqual([
    {
      file: 'jump.ogg',
      reason: 'it gives the name "jump", and so does jump.wav',
    },
    {
      file: 'jump.wav',
      reason: 'it gives the name "jump", and so does jump.ogg',
    },
  ])
})

it('leaves out names that cannot be used', () => {
  const root = project(['sound.wav', 'class.wav', '2x.wav', '---.wav'])
  const { sounds, problems } = scanSounds(root)
  expect(sounds).toEqual([])
  expect(problems.map((p) => p.file)).toEqual([
    '---.wav',
    '2x.wav',
    'class.wav',
    'sound.wav',
  ])
})

it('ignores files that are not sounds', () => {
  const root = project(['a.wav', 'notes.txt', 'b.png', '.DS_Store', '._c.wav'])
  mkdirSync(join(root, SOUNDS_DIR, 'sub.wav'))
  expect(scanSounds(root)).toEqual({
    sounds: [{ name: 'a', file: 'a.wav' }],
    problems: [],
  })
})

it('writes no file for a project without a sounds folder', () => {
  const root = project()
  expect(writeSounds(root)).toEqual({ changed: false, problems: [] })
  expect(existsSync(join(root, SOUNDS_FILE))).toBe(false)
})

it('writes the empty form for an empty folder', () => {
  const root = project([])
  writeSounds(root)
  expect(generated(root)).toBe(
    '// Generated by tico8 from the sounds folder. Do not edit.\nexport {}\n',
  )
})

it('encodes the address and breaks a long line like the formatter', () => {
  const short = renderSounds([{ name: 'a', file: "it's a b.wav" }])
  expect(short).toContain("sound('/sounds/it%27s%20a%20b.wav')")
  const file = `${'long'.repeat(12)}.wav`
  expect(renderSounds([{ name: 'long', file }])).toContain(
    `export const long = sound(\n  '/sounds/${file}',\n)`,
  )
})
