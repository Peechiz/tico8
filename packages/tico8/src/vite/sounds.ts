import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, extname, join, resolve } from 'node:path'
import type { Plugin } from 'vite'
import { camelCase } from './sprites.ts'

/** The project folder sounds live in, and the file written beside it. */
export const SOUNDS_DIR = 'sounds'
export const SOUNDS_FILE = 'sounds.ts'

/** The file types a sound can be. */
export const SOUND_TYPES = ['.wav', '.ogg', '.mp3'] as const

export interface SoundFile {
  /** The name game code imports: `bigBoss` for `big-boss.wav`. */
  name: string
  /** The file name inside the sounds folder. */
  file: string
}

/** A file in the sounds folder that was left out, and why. */
export interface SoundProblem {
  file: string
  reason: string
}

/** The longest line the formatter leaves on one line. */
const lineWidth = 80

const header = '// Generated by tico8 from the sounds folder. Do not edit.\n'

/**
 * Names the generated file cannot export: words the language keeps for
 * itself, and `sound`, which the file imports.
 */
const reserved = new Set(
  (
    'arguments await break case catch class const continue debugger default ' +
    'delete do else enum eval export extends false finally for function if ' +
    'implements import in instanceof interface let new null package private ' +
    'protected public return sound static super switch this throw true try ' +
    'typeof undefined var void while with yield'
  ).split(' '),
)

/** The text of the generated `sounds.ts`. */
export function renderSounds(files: readonly SoundFile[]): string {
  if (files.length === 0) return `${header}export {}\n`
  const lines = [...files]
    .sort((a, b) => compare(a.name, b.name))
    .map(({ name, file }) => {
      const url = `'/${SOUNDS_DIR}/${encodeURIComponent(file).replaceAll("'", '%27')}'`
      const line = `export const ${name} = sound(${url})`
      if (line.length <= lineWidth) return line
      // Broken the way the formatter breaks a call that is too long.
      return `export const ${name} = sound(\n  ${url},\n)`
    })
  return `${header}import { sound } from 'tico8/assets'\n\n${lines.join('\n')}\n`
}

/** A sound's name, or why its file cannot have one. */
function parseSoundFile(
  file: string,
): { name: string } | { reason: string } | undefined {
  // Hidden files are an editor's or the system's, never a sound.
  if (file.startsWith('.')) return undefined
  const ext = extname(file).toLowerCase()
  if (!(SOUND_TYPES as readonly string[]).includes(ext)) return undefined
  const name = camelCase(file.slice(0, -ext.length))
  if (name === '') return { reason: 'it has no letters to make a name from' }
  if (/^\p{N}/u.test(name)) {
    return {
      reason: `the name "${name}" starts with a digit, so it cannot be imported`,
    }
  }
  if (reserved.has(name)) {
    return { reason: `"${name}" is a reserved word, so it cannot be imported` }
  }
  if (!/^\p{ID_Start}\p{ID_Continue}*$/u.test(name)) {
    return { reason: `the name "${name}" cannot be used as an import` }
  }
  return { name }
}

/**
 * The sounds in a project's sounds folder, sorted by name, and the files
 * left out. A folder that is missing counts as empty.
 */
export function scanSounds(root: string): {
  sounds: SoundFile[]
  problems: SoundProblem[]
} {
  const parsed: SoundFile[] = []
  const problems: SoundProblem[] = []
  for (const file of listFiles(join(root, SOUNDS_DIR))) {
    const result = parseSoundFile(file)
    if (!result) continue
    if ('reason' in result) problems.push({ file, reason: result.reason })
    else parsed.push({ name: result.name, file })
  }

  const byName = new Map<string, SoundFile[]>()
  for (const sound of parsed) {
    byName.set(sound.name, [...(byName.get(sound.name) ?? []), sound])
  }
  const sounds: SoundFile[] = []
  for (const [name, same] of byName) {
    if (same.length === 1) {
      sounds.push(same[0]!)
      continue
    }
    for (const { file } of same) {
      const others = same.filter((other) => other.file !== file)
      problems.push({
        file,
        reason: `it gives the name "${name}", and so does ${others
          .map((other) => other.file)
          .join(' and ')}`,
      })
    }
  }

  sounds.sort((a, b) => compare(a.name, b.name))
  problems.sort((a, b) => compare(a.file, b.file))
  return { sounds, problems }
}

/**
 * Bring a project's `sounds.ts` in step with its sounds folder. Written only
 * for a project with a sounds folder, and only when its text would change.
 */
export function writeSounds(root: string): {
  changed: boolean
  problems: SoundProblem[]
} {
  if (!hasFolder(join(root, SOUNDS_DIR)))
    return { changed: false, problems: [] }
  const { sounds, problems } = scanSounds(root)
  const text = renderSounds(sounds)
  const path = join(root, SOUNDS_FILE)
  if (readText(path) === text) return { changed: false, problems }
  writeFileSync(path, text)
  return { changed: true, problems }
}

/** Keeps the project's `sounds.ts` in step with its sounds folder. */
export function sounds(): Plugin {
  let root = ''
  let warn: (message: string) => void = () => {}
  /** Warnings already shown, so a problem is reported once, not per scan. */
  let shown = new Set<string>()

  function sync() {
    const { problems } = writeSounds(root)
    const messages = problems.map(
      ({ file, reason }) =>
        `[tico8] ${SOUNDS_DIR}/${file} is left out of ${SOUNDS_FILE}: ${reason}.`,
    )
    for (const message of messages) {
      if (!shown.has(message)) warn(message)
    }
    shown = new Set(messages)
  }

  return {
    name: 'tico8:sounds',

    configResolved(config) {
      root = resolve(config.root)
      warn = (message) => config.logger.warn(message, { timestamp: true })
      sync()
    },

    configureServer(server) {
      const dir = join(root, SOUNDS_DIR)
      const out = join(root, SOUNDS_FILE)
      let timer: ReturnType<typeof setTimeout> | undefined

      server.watcher.on('all', (event, changed) => {
        const path = resolve(changed)
        // The folder's list of files is what matters. A sound saved with new
        // content keeps its name, and is swapped live elsewhere.
        const listed =
          event !== 'change' && (path === dir || dirname(path) === dir)
        // A generated file edited or deleted by hand is put back.
        if (!listed && path !== out) return
        // A rename arrives as a removal and an addition; wait for both.
        clearTimeout(timer)
        timer = setTimeout(sync, 50)
      })
      server.httpServer?.once('close', () => clearTimeout(timer))
    },
  }
}

/** Code-unit order, so the output is the same on every machine. */
function compare(a: string, b: string): number {
  return a < b ? -1 : a > b ? 1 : 0
}

function hasFolder(dir: string): boolean {
  try {
    readdirSync(dir)
    return true
  } catch (error) {
    if (isMissing(error)) return false
    throw error
  }
}

/** The names of the files directly inside a folder; none if it is missing. */
function listFiles(dir: string): string[] {
  try {
    return readdirSync(dir, { withFileTypes: true })
      .filter((entry) => entry.isFile())
      .map((entry) => entry.name)
  } catch (error) {
    if (isMissing(error)) return []
    throw error
  }
}

function readText(path: string): string | undefined {
  try {
    return readFileSync(path, 'utf8')
  } catch (error) {
    if (isMissing(error)) return undefined
    throw error
  }
}

function isMissing(error: unknown): boolean {
  const code = (error as NodeJS.ErrnoException | undefined)?.code
  return code === 'ENOENT' || code === 'ENOTDIR'
}
