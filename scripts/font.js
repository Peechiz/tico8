// `node scripts/font.js` turns the Tom Thumb font in `packages/tico8/font`
// into the data the engine draws from. `--print` writes it to the terminal
// instead of the file, which is how the test checks the file is up to date.
import { readFileSync, writeFileSync } from 'node:fs'

const source = new URL('../packages/tico8/font/tom-thumb.bdf', import.meta.url)
const target = new URL(
  '../packages/tico8/src/text/tom-thumb.ts',
  import.meta.url,
)

// The font leaves one empty column after every character; the engine adds
// that gap itself, so a glyph is that much narrower than its advance.
const SPACING = 1

/** Read a BDF font into its line height and its glyphs, in file order. */
function parse(bdf) {
  let height = 0
  let baseline = 0
  let glyph = null
  let bitmap = null
  const glyphs = []
  for (const line of bdf.split(/\r?\n/)) {
    const [word, ...rest] = line.trim().split(/\s+/)
    const numbers = rest.map(Number)
    if (bitmap && word !== 'ENDCHAR') bitmap.push(word)
    else if (word === 'FONTBOUNDINGBOX') {
      // The cell's bottom row sits `yoff` below the baseline, so the row
      // that stands on the baseline is that many up from the last.
      height = numbers[1]
      baseline = height - 1 + numbers[3]
    } else if (word === 'STARTCHAR') glyph = { name: rest[0] }
    else if (word === 'ENCODING') glyph.code = numbers[0]
    else if (word === 'DWIDTH') glyph.width = numbers[0] - SPACING
    else if (word === 'BBX') glyph.box = numbers
    else if (word === 'BITMAP') bitmap = []
    else if (word === 'ENDCHAR') {
      glyphs.push({
        char: String.fromCodePoint(glyph.code),
        width: glyph.width,
        rows: place(glyph, bitmap, height, baseline),
      })
      bitmap = null
    }
  }
  return { height, glyphs }
}

/**
 * Put a glyph's own small picture into the full cell: one number per row,
 * with column 0 in bit 0. BDF has the leftmost pixel in the highest bit.
 */
function place(glyph, bitmap, height, baseline) {
  const [w, h, xoff, yoff] = glyph.box
  const rows = new Array(height).fill(0)
  const top = baseline - yoff - (h - 1)
  bitmap.forEach((hex, i) => {
    const bits = Number.parseInt(hex, 16)
    for (let c = 0; c < w; c++) {
      if ((bits & (1 << (hex.length * 4 - 1 - c))) === 0) continue
      const x = xoff + c
      const y = top + i
      if (x < 0 || x >= glyph.width || y < 0 || y >= height) {
        throw new Error(`${glyph.name} has a pixel outside its cell`)
      }
      rows[y] |= 1 << x
    }
  })
  return rows
}

/** A character as a string literal, quoted the way the formatter wants. */
function quote(char) {
  if (char === "'") return `"'"`
  if (char === '\\') return `'\\\\'`
  if (/\p{C}/u.test(char)) {
    return `'\\u${char.codePointAt(0).toString(16).padStart(4, '0')}'`
  }
  return `'${char}'`
}

const { height, glyphs } = parse(readFileSync(source, 'utf8'))
const lines = glyphs.map(
  ({ char, width, rows }) =>
    `  [${quote(char)}, { width: ${width}, rows: [${rows.join(', ')}] }],`,
)
const output = `// Generated by scripts/font.js. Do not edit.
import type { Glyph } from './types.ts'

/** How many rows every Tom Thumb glyph has. */
export const TOM_THUMB_HEIGHT = ${height}

/** The empty columns Tom Thumb leaves between characters. */
export const TOM_THUMB_SPACING = ${SPACING}

/** Tom Thumb's ${glyphs.length} glyphs, keyed by the character. */
export const TOM_THUMB: ReadonlyMap<string, Glyph> = new Map([
${lines.join('\n')}
])
`

if (process.argv.includes('--print')) process.stdout.write(output)
else {
  writeFileSync(target, output)
  console.log(`Wrote ${glyphs.length} glyphs to ${target.pathname}`)
}
